// Parser types
export interface ParsedPage {
  Title: string;
  Content: string;
  Frontmatter: Record<string, unknown>;
  PlantUMLDiagrams: Array<{ hash: string; code: string }>;
  MermaidDiagrams: Array<{ hash: string; code: string }>;
  /** Remote image URLs referenced by the page; the renderer downloads them. */
  RemoteImages?: Array<{ url: string; filename: string }>;
}

export interface MDXParserOptions {
  stripManualNumbering?: boolean;
  convertEmoji?: boolean;
  useEmojiCommands?: boolean;
  suppressCaptionNumbers?: boolean;
  /** Document language; enables language-specific typography (vlna for cs/sk). */
  language?: string;
  /**
   * Canonical keys of all documents in the build (MDXParser.canonicalDocKey).
   * When set, cross-document links resolve to internal \hyperref targets;
   * unresolvable links degrade to plain text instead of dead URLs.
   */
  knownDocs?: Set<string>;
  /**
   * Parse $...$/$$...$$ as math. Should mirror whether the Docusaurus site
   * has remark-math/KaTeX configured; otherwise "$5 and $10" prose would be
   * swallowed as a formula.
   */
  enableMath?: boolean;
}

// Renderer types
export interface RendererOptions {
  OutputDir: string;
  Engine: 'lualatex' | 'xelatex' | 'pdflatex' | 'tectonic';
  Sections?: string[];
  StripManualNumbering?: boolean;
  ConvertEmoji?: boolean;
  SuppressCaptionNumbers?: boolean;
  SkipDiagrams?: boolean;
}

// LaTeX generator types
export interface LatexGeneratorOptions {
  Engine: 'lualatex' | 'xelatex' | 'pdflatex' | 'tectonic';
  Title: string;
  Language: string;
  Date: string;
  Author?: string;
}

export interface DocumentSection {
  Title: string;
  Content: string;
  Level: number;
  /** Canonical doc key; emitted as \label{doc:<key>} for cross-doc links. */
  LabelKey?: string;
  PlantUMLDiagrams?: Array<{ hash: string; code: string }>;
  MermaidDiagrams?: Array<{ hash: string; code: string }>;
}

// CLI types
export interface CLIOptions {
  input: string;
  output: string;
  engine: 'lualatex' | 'xelatex' | 'pdflatex' | 'tectonic';
  single: boolean;
  perLanguage: boolean;
  texOnly: boolean;
  compileOnly: boolean;
  docker: boolean;
  stripNumbering: boolean;
  convertEmoji: boolean;
  suppressCaptionNumbers: boolean;
  sections?: string;
}

// Plugin types
export interface PluginOptions {
  outputDir?: string;
  engine?: 'lualatex' | 'xelatex' | 'pdflatex' | 'tectonic';
  sections?: string[];
}
