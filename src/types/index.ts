/**
 * Core types for Docusaurus2PDF
 */

// Site and navigation types
export interface Site {
  Root: string;
  DocsDir: string;
  Sidebars: Category[];
  Pages: DocPage[];
  Config?: SiteConfig;
  DefaultLocale?: string;
  /** True when the site config references remark-math/KaTeX. */
  UsesMath?: boolean;
}

export interface SiteConfig {
  Title: string;
  Tagline?: string;
  URL?: string;
}

export interface Category {
  Type: string;
  Label: string;
  Items: SidebarItem[];
  Link?: Link;
}

export interface SidebarItem {
  Type: string;
  ID?: string;
  Label?: string;
  Items?: SidebarItem[];
  /** For type 'autogenerated': directory the items are generated from. */
  DirName?: string;
  Link?: Link;
}

/** Flattened, ordered document outline derived from the sidebars. */
export interface OrderedEntry {
  Type: 'category' | 'doc';
  /** Category heading text (Type === 'category'). */
  Label?: string;
  /** The document (Type === 'doc'). */
  Doc?: DocPage;
  /** 1-based outline depth; 1 maps to \section. */
  Level: number;
}

export interface Link {
  Type: string;
  ID: string;
}

export interface DocPage {
  Path: string;
  ID: string;
  Title: string;
  Content: string;
  Language: string;
  Frontmatter: Record<string, unknown>;
}

